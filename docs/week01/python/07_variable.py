#== 같은 이름 a 로 실험하기
#> 함수 안에서 a 를 부르면 어느 a 가 나오는지 확인한다.

# --8<-- [start:scope]
a = 5           # 전역변수

def fun1():
    a = 1       # 지역변수
    print(a)
    #(1:3)> 함수 안에서 새로 만든 변수 a → 전역 변수 a 와 별개

def fun2():
    print(a)    # 전역변수
    #(2:2)> 안에 변수 a 가 없으니 밖의 전역 변수 a 를 찾아 쓴다

def fun3():
    global a
    a = 4
    print(a)
    #(3:4)> global 을 선언하면 밖의 전역 변수 a 를 직접 가리킨다
    #(3)> 이 줄의 a = 4 는 새로 만드는 게 아니라 전역 변수 a 를 바꾸는 것

print(a)   # 5

fun1()     # 1
print(a)   # 5

fun2()     # 5
fun3()     # 4
print(a)   # 4  ← fun3 가 전역 a 를 바꿔놓음
# --8<-- [end:scope]

#! 지역변수가 있으면 함수 안에서는 지역변수가 우선.
#! 지역변수가 없으면 밖의 전역변수를 참조
#! 값을 읽는 건 그냥 되지만, 바꾸려면 global 이 필요하다.
